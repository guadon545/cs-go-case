def get_inventory_count(telegram_id):
    with get_db() as db:
        result = db.execute("""
            SELECT COUNT(*) AS total
            FROM nft_inventory
            WHERE user_id = %s
        """, (int(telegram_id),)).fetchone()

        return int(result["total"])


def get_inventory(telegram_id):
    with get_db() as db:
        rows = db.execute("""
            SELECT
                i.id AS inventory_id,
                i.nft_id,
                i.background,
                i.background_multiplier,
                i.final_price,
                i.acquired_at,
                n.code,
                n.name,
                n.rarity,
                n.image_url
            FROM nft_inventory i
            JOIN nft_catalog n ON n.id = i.nft_id
            WHERE i.user_id = %s
            ORDER BY i.acquired_at DESC
        """, (int(telegram_id),)).fetchall()

        return [dict(row) for row in rows]
