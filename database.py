
import os
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb


DATABASE_URL = os.getenv("DATABASE_URL")
START_BALANCE = 1000
INVENTORY_LIMIT = 100


# -------------------------
# DATABASE CONNECTION
# -------------------------

def get_connection():
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL не задана в переменных окружения"
        )

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=15
    )


@contextmanager
def get_db():
    connection = get_connection()

    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


# -------------------------
# DATABASE INITIALIZATION
# -------------------------

def init_db():
    with get_db() as db:

        db.execute("""
            CREATE TABLE IF NOT EXISTS users (
                telegram_id BIGINT PRIMARY KEY,
                username TEXT,
                balance BIGINT NOT NULL DEFAULT 0,
                total_clicks BIGINT NOT NULL DEFAULT 0,
                click_level INTEGER NOT NULL DEFAULT 1,
                last_click_at DOUBLE PRECISION,
                is_banned BOOLEAN NOT NULL DEFAULT FALSE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        db.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS game_id BIGINT
        """)

        db.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ
        """)

        db.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS sound_enabled BOOLEAN
            NOT NULL DEFAULT TRUE
        """)

        # Публичные игровые ID.
        db.execute("""
            CREATE SEQUENCE IF NOT EXISTS nft_game_id_seq
            START WITH 10001
        """)

        db.execute("""
            SELECT setval(
                'nft_game_id_seq',
                GREATEST(
                    COALESCE((SELECT MAX(game_id) FROM users), 10000),
                    10000
                ),
                TRUE
            )
        """)

        db.execute("""
            UPDATE users
            SET game_id = nextval('nft_game_id_seq')
            WHERE game_id IS NULL
        """)

        db.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS
            users_game_id_unique
            ON users(game_id)
        """)

        db.execute("""
            CREATE INDEX IF NOT EXISTS
            users_last_seen_idx
            ON users(last_seen)
        """)

        # Администраторы.
        db.execute("""
            CREATE TABLE IF NOT EXISTS admins (
                telegram_id BIGINT PRIMARY KEY
            )
        """)

        # Каталог NFT.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_catalog (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code TEXT UNIQUE NOT NULL,
                name TEXT NOT NULL,
                rarity TEXT NOT NULL DEFAULT 'Обычный',
                base_price BIGINT NOT NULL CHECK (base_price >= 0),
                image_url TEXT,
                is_active BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # Кейсы.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_cases (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code TEXT UNIQUE NOT NULL,
                name TEXT NOT NULL,
                price BIGINT NOT NULL CHECK (price > 0),
                image_url TEXT,
                sort_order INTEGER NOT NULL DEFAULT 0,
                is_active BOOLEAN NOT NULL DEFAULT TRUE
            )
        """)

        # NFT внутри кейсов.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_case_items (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                case_id BIGINT NOT NULL
                    REFERENCES nft_cases(id) ON DELETE CASCADE,
                nft_id BIGINT NOT NULL
                    REFERENCES nft_catalog(id),
                chance NUMERIC(12, 6) NOT NULL
                    CHECK (chance > 0 AND chance <= 100),
                UNIQUE(case_id, nft_id)
            )
        """)

        # Фоны внутри кейсов.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_case_backgrounds (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                case_id BIGINT NOT NULL
                    REFERENCES nft_cases(id) ON DELETE CASCADE,
                background TEXT NOT NULL,
                multiplier NUMERIC(10, 2) NOT NULL DEFAULT 1,
                chance NUMERIC(12, 6) NOT NULL
                    CHECK (chance > 0 AND chance <= 100),
                UNIQUE(case_id, background)
            )
        """)

        # Инвентарь игроков.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_inventory (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(telegram_id) ON DELETE CASCADE,
                nft_id BIGINT NOT NULL
                    REFERENCES nft_catalog(id),
                background TEXT NOT NULL DEFAULT 'normal',
                background_multiplier NUMERIC(10, 2)
                    NOT NULL DEFAULT 1,
                final_price BIGINT NOT NULL CHECK (final_price >= 0),
                source TEXT NOT NULL DEFAULT 'system',
                acquired_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        db.execute("""
            ALTER TABLE nft_inventory
            ALTER COLUMN background SET DEFAULT 'normal'
        """)

        db.execute("""
            CREATE INDEX IF NOT EXISTS
            nft_inventory_user_idx
            ON nft_inventory(user_id, acquired_at DESC)
        """)

        db.execute("""
            CREATE INDEX IF NOT EXISTS
            nft_inventory_price_idx
            ON nft_inventory(user_id, final_price DESC)
        """)

        # Награды, ожидающие получения или продажи.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_pending_rewards (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(telegram_id) ON DELETE CASCADE,
                nft_id BIGINT NOT NULL
                    REFERENCES nft_catalog(id),
                background TEXT NOT NULL DEFAULT 'normal',
                background_multiplier NUMERIC(10, 2)
                    NOT NULL DEFAULT 1,
                final_price BIGINT NOT NULL CHECK (final_price >= 0),
                case_code TEXT,
                batch_id UUID NOT NULL,
                status TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'claimed', 'sold')),
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                completed_at TIMESTAMPTZ
            )
        """)

        db.execute("""
            ALTER TABLE nft_pending_rewards
            ALTER COLUMN background SET DEFAULT 'normal'
        """)

        db.execute("""
            CREATE INDEX IF NOT EXISTS
            nft_pending_user_idx
            ON nft_pending_rewards(user_id, status)
        """)

        db.execute("""
            CREATE INDEX IF NOT EXISTS
            nft_pending_batch_idx
            ON nft_pending_rewards(batch_id)
        """)

        # История игровой валюты.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_g_transactions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(telegram_id) ON DELETE CASCADE,
                amount BIGINT NOT NULL,
                balance_after BIGINT NOT NULL,
                action TEXT NOT NULL,
                description TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # История открытия кейсов.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_case_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(telegram_id) ON DELETE CASCADE,
                case_code TEXT NOT NULL,
                quantity INTEGER NOT NULL,
                total_price BIGINT NOT NULL,
                batch_id UUID NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # История апгрейдов.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_upgrade_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(telegram_id) ON DELETE CASCADE,
                source_inventory_id BIGINT,
                target_nft_id BIGINT,
                target_background TEXT,
                multiplier NUMERIC(10, 2),
                chance NUMERIC(10, 4),
                won BOOLEAN NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # История крафта.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_craft_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(telegram_id) ON DELETE CASCADE,
                items_used JSONB NOT NULL,
                total_price BIGINT NOT NULL,
                reward_inventory_id BIGINT,
                reward_nft_id BIGINT,
                reward_price BIGINT NOT NULL,
                multiplier NUMERIC(10, 4),
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # Статистика игроков.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_player_stats (
                user_id BIGINT PRIMARY KEY
                    REFERENCES users(telegram_id) ON DELETE CASCADE,
                cases_opened BIGINT NOT NULL DEFAULT 0,
                upgrades_played BIGINT NOT NULL DEFAULT 0,
                upgrades_won BIGINT NOT NULL DEFAULT 0,
                crafts_completed BIGINT NOT NULL DEFAULT 0,
                nft_sold BIGINT NOT NULL DEFAULT 0,
                total_spent BIGINT NOT NULL DEFAULT 0,
                total_earned BIGINT NOT NULL DEFAULT 0
            )
        """)

        # Журнал действий администратора.
        db.execute("""
            CREATE TABLE IF NOT EXISTS nft_admin_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                admin_telegram_id BIGINT NOT NULL,
                target_telegram_id BIGINT,
                action TEXT NOT NULL,
                details JSONB,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # Создаём статистику для всех существующих игроков.
        db.execute("""
            INSERT INTO nft_player_stats (user_id)
            SELECT telegram_id
            FROM users
            ON CONFLICT (user_id) DO NOTHING
        """)


