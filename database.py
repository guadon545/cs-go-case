def get_balance(telegram_id):
    with get_db() as db:
        result = db.execute("""
            SELECT balance
            FROM users
            WHERE telegram_id = %s
        """, (int(telegram_id),)).fetchone()

        return int(result["balance"]) if result else 0


def change_balance(
    telegram_id,
    amount,
    action="admin",
    description=None
):
    telegram_id = int(telegram_id)
    amount = int(amount)

    with get_db() as db:
        player = db.execute("""
            SELECT balance
            FROM users
            WHERE telegram_id = %s
            FOR UPDATE
        """, (telegram_id,)).fetchone()

        if not player:
            raise ValueError("Игрок не найден")

        new_balance = int(player["balance"]) + amount

        if new_balance < 0:
            raise ValueError("Недостаточно G")

        db.execute("""
            UPDATE users
            SET balance = %s
            WHERE telegram_id = %s
        """, (new_balance, telegram_id))

        db.execute("""
            INSERT INTO nft_g_transactions (
                user_id,
                amount,
                balance_after,
                action,
                description
            )
            VALUES (%s, %s, %s, %s, %s)
        """, (
            telegram_id,
            amount,
            new_balance,
            action,
            description
        ))

        return new_balance


