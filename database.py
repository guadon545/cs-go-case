def register_user(telegram_id, username=None):
    telegram_id = int(telegram_id)

    with get_db() as db:

        # При повторном входе не меняем игровой ID
        # и не перезаписываем существующий username на NULL.
        player = db.execute("""
            INSERT INTO users (
                telegram_id,
                username,
                balance,
                last_seen
            )
            VALUES (%s, %s, %s, NOW())
            ON CONFLICT (telegram_id)
            DO UPDATE SET
                username = COALESCE(
                    EXCLUDED.username,
                    users.username
                ),
                last_seen = NOW()
            RETURNING *
        """, (
            telegram_id,
            username,
            START_BALANCE
        )).fetchone()

        # Назначаем ID только если его ещё нет.
        if player["game_id"] is None:
            player = db.execute("""
                UPDATE users
                SET game_id = nextval('nft_game_id_seq')
                WHERE telegram_id = %s
                RETURNING *
            """, (telegram_id,)).fetchone()

        db.execute("""
            INSERT INTO nft_player_stats (user_id)
            VALUES (%s)
            ON CONFLICT (user_id) DO NOTHING
        """, (telegram_id,))

        return dict(player)


