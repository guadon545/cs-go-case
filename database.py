
import os
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


DATABASE_URL = os.environ.get("DATABASE_URL")
INVENTORY_LIMIT = 100


@contextmanager
def get_db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL не настроен в Render")

    with psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=20
    ) as conn:
        yield conn


def init_db():
    """Создание таблиц и безопасное обновление старой базы."""

    tables = [
        """
        CREATE TABLE IF NOT EXISTS users (
            telegram_id BIGINT PRIMARY KEY,
            username TEXT,
            balance BIGINT DEFAULT 0,
            total_clicks BIGINT DEFAULT 0,
            click_level INTEGER DEFAULT 1,
            last_click_at DOUBLE PRECISION DEFAULT 0,
            is_banned INTEGER DEFAULT 0,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS admins (
            telegram_id BIGINT PRIMARY KEY
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS skins (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            rarity TEXT DEFAULT 'Consumer',
            price BIGINT DEFAULT 0
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS cases (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            price_dc BIGINT DEFAULT 0
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS inventory (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(telegram_id),
            skin_id BIGINT NOT NULL REFERENCES skins(id),
            quantity BIGINT DEFAULT 1,
            acquired_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS transactions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT,
            amount BIGINT,
            action TEXT,
            admin_id BIGINT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS admin_logs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            admin_id BIGINT,
            action TEXT,
            target_id BIGINT,
            details TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS profile_stats (
            user_id BIGINT PRIMARY KEY REFERENCES users(telegram_id),
            opened_cases BIGINT DEFAULT 0,
            successful_upgrades BIGINT DEFAULT 0
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS item_history (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(telegram_id),
            skin_id BIGINT,
            skin_name TEXT NOT NULL,
            skin_price BIGINT DEFAULT 0,
            source TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """
    ]

    with get_db() as db:
        for sql in tables:
            db.execute(sql)

        # Добавляем ссылку на изображение скина.
        db.execute("""
            ALTER TABLE skins
            ADD COLUMN IF NOT EXISTS image_url TEXT
        """)

        # Убираем старое ограничение, объединявшее одинаковые скины.
        db.execute("""
            DO $$
            DECLARE constraint_row RECORD;
            BEGIN
                FOR constraint_row IN
                    SELECT conname
                    FROM pg_constraint
                    WHERE conrelid = 'inventory'::regclass
                    AND contype = 'u'
                LOOP
                    EXECUTE format(
                        'ALTER TABLE inventory DROP CONSTRAINT %I',
                        constraint_row.conname
                    );
                END LOOP;
            END $$;
        """)

        # Разделяем старые количества на отдельные предметы.
        db.execute("""
            INSERT INTO inventory (user_id, skin_id, quantity, acquired_at)
            SELECT
                inventory.user_id,
                inventory.skin_id,
                1,
                inventory.acquired_at
            FROM inventory
            CROSS JOIN LATERAL generate_series(
                1,
                GREATEST(inventory.quantity, 1) - 1
            ) AS item_number
            WHERE inventory.quantity > 1
        """)

        db.execute("""
            UPDATE inventory
            SET quantity = 1
            WHERE quantity IS NULL OR quantity <> 1
        """)

        db.execute("""
            CREATE INDEX IF NOT EXISTS inventory_user_idx
            ON inventory(user_id)
        """)


def register_user(telegram_id, username=None):
    with get_db() as db:
        db.execute("""
            INSERT INTO users (telegram_id, username)
            VALUES (%s, %s)
            ON CONFLICT (telegram_id)
            DO UPDATE SET username = EXCLUDED.username
        """, (telegram_id, username))

        db.execute("""
            INSERT INTO profile_stats (user_id)
            VALUES (%s)
            ON CONFLICT (user_id) DO NOTHING
        """, (telegram_id,))


