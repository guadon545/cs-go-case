def is_admin(telegram_id):
    with get_db() as db:
        result = db.execute("""
            SELECT 1
            FROM admins
            WHERE telegram_id = %s
        """, (int(telegram_id),)).fetchone()

        return result is not None


def log_admin_action(
    admin_telegram_id,
    action,
    target_telegram_id=None,
    details=None
):
    with get_db() as db:
        db.execute("""
            INSERT INTO nft_admin_logs (
                admin_telegram_id,
                target_telegram_id,
                action,
                details
            )
            VALUES (%s, %s, %s, %s)
        """, (
            int(admin_telegram_id),
            int(target_telegram_id) if target_telegram_id else None,
            action,
            Jsonb(details) if details is not None else None
        ))


