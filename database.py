def add_inventory_skin(user_id, skin_id, quantity=1):
    quantity = int(quantity)

    if quantity <= 0:
        raise ValueError("Количество должно быть больше нуля")

    with get_db() as db:
        db.execute("""
            INSERT INTO inventory (user_id, skin_id, quantity)
            VALUES (%s, %s, %s)
            ON CONFLICT (user_id, skin_id)
            DO UPDATE SET quantity =
                inventory.quantity + EXCLUDED.quantity
        """, (user_id, skin_id, quantity))


def remove_inventory_skin(user_id, skin_id, quantity=1):
    quantity = int(quantity)

    if quantity <= 0:
        raise ValueError("Количество должно быть больше нуля")

    with get_db() as db:
        row = db.execute("""
            SELECT quantity
            FROM inventory
            WHERE user_id = %s AND skin_id = %s
            FOR UPDATE
        """, (user_id, skin_id)).fetchone()

        if not row or row["quantity"] < quantity:
            return False

        if row["quantity"] == quantity:
            db.execute("""
                DELETE FROM inventory
                WHERE user_id = %s AND skin_id = %s
            """, (user_id, skin_id))
        else:
            db.execute("""
                UPDATE inventory
                SET quantity = quantity - %s
                WHERE user_id = %s AND skin_id = %s
            """, (quantity, user_id, skin_id))

        return True


def get_inventory(user_id):
    with get_db() as db:
        rows = db.execute("""
            SELECT
                skins.id AS skin_id,
                skins.name,
                skins.rarity,
                skins.price,
                inventory.quantity
            FROM inventory
            JOIN skins ON skins.id = inventory.skin_id
            WHERE inventory.user_id = %s
            ORDER BY skins.price DESC
        """, (user_id,)).fetchall()

        return [dict(row) for row in rows]


def record_item_history(user_id, skin_id, source):
    with get_db() as db:
        skin = db.execute("""
            SELECT name, price
            FROM skins
            WHERE id = %s
        """, (skin_id,)).fetchone()

        if not skin:
            return

        db.execute("""
            INSERT INTO item_history
            (user_id, skin_id, skin_name, skin_price, source)
            VALUES (%s, %s, %s, %s, %s)
        """, (
            user_id,
            skin_id,
            skin["name"],
            skin["price"],
            source
        ))


def increment_opened_cases(user_id, amount=1):
    with get_db() as db:
        db.execute("""
            INSERT INTO profile_stats (user_id)
            VALUES (%s)
            ON CONFLICT (user_id) DO NOTHING
        """, (user_id,))

        db.execute("""
            UPDATE profile_stats
            SET opened_cases = opened_cases + %s
            WHERE user_id = %s
        """, (int(amount), user_id))


def increment_successful_upgrades(user_id):
    with get_db() as db:
        db.execute("""
            INSERT INTO profile_stats (user_id)
            VALUES (%s)
            ON CONFLICT (user_id) DO NOTHING
        """, (user_id,))

        db.execute("""
            UPDATE profile_stats
            SET successful_upgrades = successful_upgrades + 1
            WHERE user_id = %s
        """, (user_id,))


def get_profile_stats(user_id):
    with get_db() as db:
        stats = db.execute("""
            SELECT
                users.balance,
                COALESCE(profile_stats.opened_cases, 0) AS opened_cases,
                COALESCE(profile_stats.successful_upgrades, 0)
                    AS successful_upgrades
            FROM users
            LEFT JOIN profile_stats
                ON profile_stats.user_id = users.telegram_id
            WHERE users.telegram_id = %s
        """, (user_id,)).fetchone()

        best_item = db.execute("""
            SELECT
                skin_name AS name,
                skin_price AS price,
                source,
                created_at
            FROM item_history
            WHERE user_id = %s
            ORDER BY skin_price DESC, id ASC
            LIMIT 1
        """, (user_id,)).fetchone()

        return {
            "balance": stats["balance"] if stats else 0,
            "opened_cases": stats["opened_cases"] if stats else 0,
            "successful_upgrades": (
                stats["successful_upgrades"] if stats else 0
            ),
            "best_item": dict(best_item) if best_item else None
        }


